// Package packer builds phase-scoped repository context packs (M7 helper).
package packer

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/Thomas-Pietsch/dudes/internal/compact"
	"github.com/Thomas-Pietsch/dudes/internal/phase"
	ws "github.com/Thomas-Pietsch/dudes/internal/workspace"
)

const DefaultOutputRel = ".dudes/context_pack.md"

// Config for the Repomix (or compatible) CLI.
type Config struct {
	Bin      string        // default "repomix"
	Timeout  time.Duration // 0 = 2m
	Output   string        // relative path; default DefaultOutputRel
	Extra    []string      // additional CLI flags after defaults
	Compress bool          // pass --compress (default true)
}

// DefaultConfig returns orchestrator-safe defaults (Repomix).
func DefaultConfig() Config {
	return Config{
		Bin:      "repomix",
		Timeout:  2 * time.Minute,
		Output:   DefaultOutputRel,
		Compress: true,
	}
}

// Resolve applies defaults.
func (c Config) Resolve() Config {
	d := DefaultConfig()
	if c.Bin == "" {
		c.Bin = d.Bin
	}
	if c.Timeout <= 0 {
		c.Timeout = d.Timeout
	}
	if c.Output == "" {
		c.Output = d.Output
	}
	return c
}

// IncludesFor returns narrow globs for a lifecycle phase (TREND: phase-scoped packs).
func IncludesFor(id phase.ID, product string) []string {
	if product == "" {
		product = "product"
	}
	switch id {
	case phase.Idea, phase.Strategy:
		return []string{"MISSION.md", "CORE.md", "FEATURES.md", "ARCHITECTURE.md", "*.md"}
	case phase.Spec:
		return []string{product + "_IDEA.md", product + "_PS.md", "FEATURES.md", "CORE.md", "MISSION.md"}
	case phase.TestAuthoring:
		return []string{product + "_PRD.md", "tests/**", "**/*_test.go"}
	case phase.Implementation:
		return []string{"cmd/**", "internal/**", "go.mod", product + "_PRD.md", product + "_FIX.md"}
	case phase.QA:
		return []string{"**/*_test.go", "tests/**", product + "_PRD.md", product + "_QR.md"}
	case phase.Documentation:
		return []string{"README.md", "docs/**", product + "_PRD.md", product + "_QR.md"}
	default:
		return []string{"*.md", "cmd/**", "internal/**", "go.mod"}
	}
}

// LookPath reports whether the packer binary is available.
func LookPath(bin string) error {
	if bin == "" {
		bin = "repomix"
	}
	_, err := exec.LookPath(bin)
	if err != nil {
		return fmt.Errorf("%s not found on PATH (install Repomix or use -stub)", bin)
	}
	return nil
}

// Run invokes Repomix into cfg.Output with phase-scoped includes.
func Run(ctx context.Context, workspace string, includes []string, cfg Config) (rel string, err error) {
	cfg = cfg.Resolve()
	if len(includes) == 0 {
		includes = []string{"*.md"}
	}
	rel = filepath.ToSlash(cfg.Output)
	absOut := filepath.Join(workspace, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(absOut), 0o755); err != nil {
		return "", err
	}

	args := []string{
		"--output", absOut,
		"--style", "markdown",
		"--include", strings.Join(includes, ","),
	}
	if cfg.Compress {
		args = append(args, "--compress")
	}
	args = append(args, cfg.Extra...)

	ctx, cancel := context.WithTimeout(ctx, cfg.Timeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, cfg.Bin, args...)
	cmd.Dir = workspace
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(stderr.String())
		if msg == "" {
			msg = strings.TrimSpace(stdout.String())
		}
		if msg == "" {
			msg = err.Error()
		}
		return "", fmt.Errorf("packer: %s", truncate(msg, 800))
	}
	if _, err := os.Stat(absOut); err != nil {
		return "", fmt.Errorf("packer: output missing after run: %s", rel)
	}
	return rel, nil
}

// WriteStubPack writes a minimal pack without Repomix (offline / -stub).
func WriteStubPack(workspace string, includes []string, outputRel string) (rel string, err error) {
	if outputRel == "" {
		outputRel = DefaultOutputRel
	}
	rel = filepath.ToSlash(outputRel)
	files, err := collectFiles(workspace, includes)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# Context pack (stub)\n\n")
	b.WriteString("Generated by dudes -stub without Repomix. Paths only + short excerpts.\n\n")
	fmt.Fprintf(&b, "## Includes\n\n`%s`\n\n", strings.Join(includes, "`, `"))
	b.WriteString("## Files\n\n")
	for _, f := range files {
		fmt.Fprintf(&b, "### %s\n\n", f)
		data, err := os.ReadFile(filepath.Join(workspace, filepath.FromSlash(f)))
		if err != nil {
			continue
		}
		excerpt := string(data)
		if len(excerpt) > 1200 {
			excerpt = excerpt[:1200] + "\n…\n"
		}
		b.WriteString("```\n")
		b.WriteString(excerpt)
		if !strings.HasSuffix(excerpt, "\n") {
			b.WriteString("\n")
		}
		b.WriteString("```\n\n")
	}
	if len(files) == 0 {
		b.WriteString("(no matching files)\n")
	}
	abs := filepath.Join(workspace, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(abs, []byte(b.String()), 0o644); err != nil {
		return "", err
	}
	return rel, nil
}

// Read loads pack content if present (empty ok).
func Read(workspace, rel string) (string, bool, error) {
	if rel == "" {
		rel = DefaultOutputRel
	}
	data, err := os.ReadFile(filepath.Join(workspace, filepath.FromSlash(rel)))
	if err != nil {
		if os.IsNotExist(err) {
			return "", false, nil
		}
		return "", false, err
	}
	return string(data), true, nil
}

// TruncateForPrompt caps pack size for LLM injection (F28-lite head/tail).
func TruncateForPrompt(s string, max int) string {
	if max <= 0 {
		max = 24000
	}
	return compact.Text(s, max)
}

func collectFiles(workspace string, includes []string) ([]string, error) {
	seen := map[string]bool{}
	var out []string
	err := filepath.Walk(workspace, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return nil
		}
		if info.IsDir() {
			if info.Name() == "bin" || ws.Foreign(workspace, path) {
				return filepath.SkipDir
			}
			return nil
		}
		rel, err := filepath.Rel(workspace, path)
		if err != nil {
			return nil
		}
		rel = filepath.ToSlash(rel)
		if strings.HasPrefix(rel, ".dudes/") {
			return nil
		}
		for _, pat := range includes {
			if matchGlob(pat, rel) {
				if !seen[rel] {
					seen[rel] = true
					out = append(out, rel)
				}
				break
			}
		}
		return nil
	})
	return out, err
}

// matchGlob supports *, **, and simple path patterns.
func matchGlob(pattern, path string) bool {
	pattern = filepath.ToSlash(pattern)
	path = filepath.ToSlash(path)
	if pattern == path {
		return true
	}
	if strings.Contains(pattern, "**") {
		// prefix/** or **/suffix or a/**/b
		parts := strings.Split(pattern, "**")
		if len(parts) == 2 {
			pre := strings.TrimSuffix(parts[0], "/")
			suf := strings.TrimPrefix(parts[1], "/")
			if pre != "" && !strings.HasPrefix(path, pre+"/") && path != pre {
				return false
			}
			if suf == "" {
				return true
			}
			if strings.HasPrefix(suf, "*.") {
				return strings.HasSuffix(path, suf[1:]) // *.go → .go
			}
			return strings.HasSuffix(path, suf) || strings.Contains(path, "/"+suf) || matchSimple(suf, filepath.Base(path))
		}
	}
	return matchSimple(pattern, path) || matchSimple(pattern, filepath.Base(path))
}

func matchSimple(pattern, name string) bool {
	ok, err := filepath.Match(pattern, name)
	return err == nil && ok
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}
