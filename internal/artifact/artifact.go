// Package artifact maps phases to durable files and reads/writes them under the workspace.
package artifact

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/Thomas-Pietsch/dudes/internal/phase"
	"github.com/Thomas-Pietsch/dudes/internal/workspace"
)

// Spec describes the primary artifact produced by a phase (MVP: one file each).
type Spec struct {
	Phase   phase.ID
	RelPath string // may contain "{product}"
}

// DefaultRegistry is the CORE-aligned artifact map (expand later for TA, multi-file).
var DefaultRegistry = []Spec{
	{phase.Idea, "{product}_IDEA.md"},
	{phase.Strategy, "{product}_PS.md"},
	{phase.Spec, "{product}_PRD.md"},
	{phase.TestAuthoring, "tests/{product}_smoke_test.go"},
	{phase.QA, "{product}_QR.md"},
	{phase.Documentation, "docs/USER.md"},
}

// Path resolves the relative artifact path for a phase, if any.
func Path(product string, id phase.ID) (rel string, ok bool) {
	if product == "" {
		product = "product"
	}
	for _, s := range DefaultRegistry {
		if s.Phase == id {
			return strings.ReplaceAll(s.RelPath, "{product}", product), true
		}
	}
	return "", false
}

// Abs joins workspace and relative path (must stay under workspace — F43).
func Abs(workspaceRoot, rel string) string {
	abs, err := workspace.Resolve(workspaceRoot, rel)
	if err != nil {
		// Fail closed: return a path that will not exist under root.
		return filepath.Join(filepath.Clean(workspaceRoot), ".dudes", "invalid-escape")
	}
	return abs
}

// Exists reports whether the file exists.
func Exists(workspaceRoot, rel string) bool {
	_, err := workspace.Resolve(workspaceRoot, rel)
	if err != nil {
		return false
	}
	_, err = os.Stat(Abs(workspaceRoot, rel))
	return err == nil
}

// NonEmpty reports exists and size > 0.
func NonEmpty(workspaceRoot, rel string) (bool, error) {
	if _, err := workspace.Resolve(workspaceRoot, rel); err != nil {
		return false, err
	}
	fi, err := os.Stat(Abs(workspaceRoot, rel))
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	return fi.Size() > 0, nil
}

// Write creates parent dirs and writes content (0644).
func Write(workspaceRoot, rel string, content []byte) error {
	abs, err := workspace.Resolve(workspaceRoot, rel)
	if err != nil {
		return fmt.Errorf("write %s: %w", rel, err)
	}
	if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
		return fmt.Errorf("mkdir for %s: %w", rel, err)
	}
	if err := os.WriteFile(abs, content, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", rel, err)
	}
	return nil
}

// Read loads file bytes.
func Read(workspaceRoot, rel string) ([]byte, error) {
	abs, err := workspace.Resolve(workspaceRoot, rel)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", rel, err)
	}
	data, err := os.ReadFile(abs)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", rel, err)
	}
	return data, nil
}

// StubContent returns placeholder body for a phase (M2 fake worker).
func StubContent(id phase.ID, product, prompt string) string {
	if prompt == "" {
		prompt = "(no prompt)"
	}
	switch id {
	case phase.Idea:
		return "# Idea\n\n" + prompt + "\n"
	case phase.Strategy:
		return "# Product Strategy — " + product + "\n\n## Intent\n\n" + prompt + "\n\n## Status\n\ndraft (engine stub)\n"
	case phase.Spec:
		return "# PRD — " + product + "\n\n## Summary\n\n" + prompt + "\n\n### Requirement: greet\nThe CLI SHALL print a greeting that includes the product name.\n\n#### Scenario: default run\n- GIVEN the binary is built\n- WHEN the user runs it with no arguments\n- THEN stdout contains the product name\n"
	case phase.TestAuthoring:
		return "package smoke_test\n\nimport \"testing\"\n\n// Stub smoke test authored by dudes (test_authoring).\n// Covers requirement greet (F37).\nfunc TestSmoke(t *testing.T) {\n\tt.Log(\"dudes stub: greet — " + product + " — " + prompt + "\")\n}\n"
	case phase.QA:
		return "# QA Report — " + product + "\n\n## Result\n\nstub — not executed\n"
	case phase.Documentation:
		return "# User docs — " + product + "\n\nStub generated by engine.\n"
	default:
		return "# " + string(id) + "\n\nstub\n"
	}
}

// TAContent returns the companion technical-architecture stub (F13 one-spec-set).
func TAContent(product, prompt string) string {
	if prompt == "" {
		prompt = "(no prompt)"
	}
	return "# Technical Architecture — " + product + "\n\n## Intent\n\n" + prompt + "\n\n## Components\n\n- TBD (engine stub)\n\n## Notes\n\nCompanion to `" + product + "_PRD.md` (one spec set).\n"
}

// TAPath returns `{product}_TA.md`.
func TAPath(product string) string {
	if product == "" {
		product = "product"
	}
	return product + "_TA.md"
}

// TasksPath returns `{product}_TASKS.md` (F39 converge-to-tasks).
func TasksPath(product string) string {
	if product == "" {
		product = "product"
	}
	return product + "_TASKS.md"
}
